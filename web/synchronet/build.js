// Build the Synchronet web bundle into dist/webv4/, laid out like webv4
// itself so installing is one copy.
//
//   node build.js              typecheck, compile, bundle, copy
//   node build.js --typecheck  typecheck only
//   node build.js --test       build, then run the node tests in test/
//
// TypeScript (src/) is compiled to ES5 by tsc, then each entry point is
// bundled by esbuild into one self-contained script Synchronet can load():
// no require, import or export in the output.
const fs = require("fs");
const path = require("path");
const childProcess = require("child_process");

const dir = __dirname;
const dist = path.join(dir, "dist", "webv4");
const buildDir = path.join(dir, "build");

function firstExisting(paths) {
  for (const p of paths) if (fs.existsSync(p)) return p;
  return null;
}

const toolDirs = [path.join(dir, "node_modules")];

function tscPath() {
  const p = firstExisting(toolDirs.map((d) => path.join(d, "typescript", "lib", "tsc.js")));
  if (!p) throw new Error("TypeScript not found: run npm install in web/synchronet");
  return p;
}

function esbuild() {
  const p = firstExisting(toolDirs.map((d) => path.join(d, "esbuild")));
  if (!p) throw new Error("esbuild not found: run npm install in web/synchronet");
  return require(p);
}

function tsc(project) {
  const r = childProcess.spawnSync(process.execPath, [tscPath(), "-p", path.join(dir, project)], { stdio: "inherit" });
  if (r.status !== 0) process.exit(r.status || 1);
}

const webv4Head = [
  "var settings = load('modopts.js', 'web') || { web_directory: '../webv4' };",
  "load(settings.web_directory + '/lib/init.js');",
  "load(settings.web_lib + 'auth.js');",
];

// out: path under dist/webv4; banner: lines before the bundle; footer: after.
const entries = [
  {
    src: "entries/api.js",
    out: "root/api/avatarchat.ssjs",
    banner: webv4Head.concat(["load('json-client.js');", "load('http.js');"]),
  },
  {
    src: "entries/upload.js",
    out: "root/api/avatarchat-upload.ssjs",
    banner: webv4Head,
  },
  {
    src: "entries/events.js",
    out: "lib/events/avatarchat.js",
    globalName: "AvatarChatEvents",
    banner: ["load('json-client.js');"],
    // events.ssjs calls cycle() and dispose() on the scope load() returns.
    footer: [
      "function cycle() { AvatarChatEvents.cycle(); }",
      "function dispose() { AvatarChatEvents.dispose(); }",
      "js.on_exit('try { if (typeof dispose === \"function\") dispose(); } catch (e) {}');",
      "this;",
    ],
  },
  {
    src: "entries/page.js",
    out: "lib/avatarchat-page.js",
    globalName: "AvatarChatPage",
    banner: [],
  },
];

const copies = [
  ["pages/avatarchat.xjs", "pages/avatarchat.xjs"],
  ["browser/app.js", "root/avatarchat/app.js"],
  ["browser/app.css", "root/avatarchat/app.css"],
];

async function build() {
  tsc("tsconfig.json");
  if (fs.existsSync(buildDir)) fs.rmSync(buildDir, { recursive: true, force: true });
  tsc("tsconfig.build.json");
  const eb = esbuild();
  for (const e of entries) {
    const outfile = path.join(dist, e.out);
    await eb.build({
      entryPoints: [path.join(buildDir, e.src)],
      bundle: true,
      charset: "ascii",
      format: "iife",
      globalName: e.globalName,
      target: "es5",
      platform: "neutral",
      outfile: outfile,
      banner: { js: ["// Avatar Chat web (avatar_chat_universal/web/synchronet). Generated by build.js from src/; do not edit."].concat(e.banner).join("\n") },
      footer: e.footer ? { js: e.footer.join("\n") } : undefined,
      logLevel: "warning",
    });
    let text = fs.readFileSync(outfile, "utf8").replace(/"use strict";\s*/g, "");
    // No ES2015 left for SpiderMonkey 1.8.5 to trip on.
    for (const bad of ["=>", "`", "\nconst ", "\nlet ", " class "]) {
      if (text.indexOf(bad) >= 0) throw new Error(e.out + ": output still contains " + JSON.stringify(bad));
    }
    fs.writeFileSync(outfile, text);
    console.log("built " + path.relative(dir, outfile));
  }
  for (const [from, to] of copies) {
    const outfile = path.join(dist, to);
    fs.mkdirSync(path.dirname(outfile), { recursive: true });
    fs.copyFileSync(path.join(dir, from), outfile);
    console.log("copied " + path.relative(dir, outfile));
  }
}

// The node tests load the pure modules (no Synchronet globals) bundled
// from src/ as one CommonJS file, test/build/lib.js.
async function runTests() {
  await esbuild().build({
    entryPoints: [path.join(dir, "test", "lib.ts")],
    bundle: true,
    format: "cjs",
    platform: "node",
    outfile: path.join(dir, "test", "build", "lib.js"),
    logLevel: "warning",
  });
  const files = fs.readdirSync(path.join(dir, "test")).filter((f) => /\.test\.js$/.test(f)).sort();
  const r = childProcess.spawnSync(process.execPath, ["--test"].concat(files.map((f) => path.join(dir, "test", f))), { stdio: "inherit" });
  if (r.status !== 0) process.exit(1);
}

(async function () {
  if (process.argv.includes("--typecheck")) return tsc("tsconfig.json");
  await build();
  if (process.argv.includes("--test")) await runTests();
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
